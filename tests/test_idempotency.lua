describe("idempotency", function()
  it("builds stable key", function()
    local k = CrusaderStrikeIdempotency.MakeKey("CrusaderStrike", "Snipy", 1730000000, 36)
    eq(k, "CrusaderStrike|Snipy|1730000000|36")
  end)

  it("floors fractional times", function()
    local k = CrusaderStrikeIdempotency.MakeKey("R", "C", 10.9, 389)
    eq(k, "R|C|10|389")
  end)

  it("parses keys", function()
    local p = CrusaderStrikeIdempotency.ParseKey("A|B|12|36")
    eq(p.realm, "A")
    eq(p.character, "B")
    eq(p.startTimeUnix, 12)
    eq(p.instanceId, 36)
  end)

  it("addon_run_id equals key", function()
    local k = CrusaderStrikeIdempotency.MakeKey("A", "B", 1, 2)
    eq(CrusaderStrikeIdempotency.ToAddonRunId(k), k)
  end)
end)
